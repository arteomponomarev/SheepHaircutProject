using System.Collections.Generic;
using UnityEngine;

namespace ShearAndGrow.Farm
{
    /// <summary>
    /// Visual representation of a building instance. The ONLY seam between building data and rendering: a 3D prefab
    /// today, a pre-rendered sprite prefab later — both implement this and are positioned from grid data.
    /// </summary>
    public interface IBuildingView
    {
        string InstanceId { get; }
        Transform ViewRoot { get; }
        Transform LabelAnchor { get; }
        Collider HitArea { get; }
        void Bind(BuildingInstanceState state, FarmBuildingDefinition def);
        void SetWorldPosition(Vector3 footprintCenter, bool smooth);
        /// <summary>0 foundation, 1 walls, 2 roof, 3 details, 4 completed; <paramref name="stageT"/> 0..1 inside the stage.</summary>
        void SetConstruction(int stage, float stageT);
        void SetGhost(Material ghostMaterial, bool on);
        void SetGhostTint(Color c);
        void SetConnections(int neighbourMask);
        /// <summary>Visual variant of a building level (same footprint and pivot).</summary>
        void SetLevel(int level);
        void Pop();
    }

    /// <summary>
    /// 3D implementation. Prefab layout (generated by the farm scene builder, replaceable by final art):
    /// View/Stage_Foundation, View/Stage_Walls, View/Stage_Roof, View/Stage_Details (all optional), a trigger HitArea
    /// on the FarmInteractable layer and a LabelAnchor. Pivot = footprint centre on the ground. Construction only
    /// changes transforms (no instantiation, no physics).
    /// </summary>
    public class BuildingView : MonoBehaviour, IBuildingView
    {
        [SerializeField] private Transform _viewRoot;
        [SerializeField] private Transform _labelAnchor;
        [SerializeField] private Collider _hitArea;
        [Header("Construction stage groups (optional)")]
        [SerializeField] private Transform _foundation;
        [SerializeField] private Transform _walls;
        [SerializeField] private Transform _roof;
        [SerializeField] private Transform _details;
        [Tooltip("Height the roof drops from while it is being placed (m).")]
        [SerializeField] private float _roofDrop = 1.6f;

        static readonly int BaseColorId = Shader.PropertyToID("_BaseColor");

        Renderer[] _renderers;
        Material[][] _originalMats;
        MaterialPropertyBlock _mpb;
        bool _ghost;
        Vector3 _targetPos, _vel;
        bool _moving;
        float _pop = -1f;
        Vector3 _roofBase;
        bool _roofBaseSet;

        public string InstanceId { get; private set; }
        public string TypeId { get; private set; }
        public FarmBuildingDefinition Definition { get; private set; }
        public Transform ViewRoot => _viewRoot != null ? _viewRoot : transform;
        public Transform LabelAnchor => _labelAnchor != null ? _labelAnchor : transform;
        public Collider HitArea => _hitArea;
        public bool IsGhost => _ghost;

        public void Configure(Transform viewRoot, Transform labelAnchor, Collider hit, Transform foundation, Transform walls, Transform roof, Transform details)
        {
            _viewRoot = viewRoot; _labelAnchor = labelAnchor; _hitArea = hit;
            _foundation = foundation; _walls = walls; _roof = roof; _details = details;
        }

        Renderer[] Renderers => _renderers != null && _renderers.Length > 0 ? _renderers : (_renderers = ViewRoot.GetComponentsInChildren<Renderer>(true));

        public virtual void Bind(BuildingInstanceState state, FarmBuildingDefinition def)
        {
            InstanceId = state != null ? state.instanceId : null;
            TypeId = def != null ? def.Id : null;
            Definition = def;
            name = (def != null ? def.DisplayName : "Building") + (state != null ? " [" + state.instanceId + "]" : " (ghost)");
        }

        public void SetWorldPosition(Vector3 p, bool smooth)
        {
            _targetPos = p;
            if (!smooth) { transform.position = p; _moving = false; _vel = Vector3.zero; }
            else _moving = true;
        }

        public void SetConstruction(int stage, float t)
        {
            if (_roof != null && !_roofBaseSet) { _roofBase = _roof.localPosition; _roofBaseSet = true; }
            t = Mathf.Clamp01(t);
            SetGroup(_foundation, true, Vector3.one);
            if (stage >= 4)
            {
                SetGroup(_walls, true, Vector3.one);
                SetGroup(_roof, true, Vector3.one);
                if (_roof != null) _roof.localPosition = _roofBase;
                SetGroup(_details, true, Vector3.one);
                return;
            }
            // walls rise from the ground during stage 1
            float walls = stage == 0 ? 0f : stage == 1 ? Mathf.SmoothStep(0f, 1f, t) : 1f;
            SetGroup(_walls, walls > 0.001f, new Vector3(1f, Mathf.Max(0.001f, walls), 1f));
            // roof drops in during stage 2 (ease-out with a small bounce)
            bool roofOn = stage >= 2;
            SetGroup(_roof, roofOn, Vector3.one);
            if (_roof != null && roofOn)
            {
                float e = stage == 2 ? EaseOutBack(t) : 1f;
                _roof.localPosition = _roofBase + Vector3.up * (1f - e) * _roofDrop;
            }
            // details pop in during stage 3
            float d = stage >= 3 ? EaseOutBack(t) : 0f;
            SetGroup(_details, d > 0.001f, Vector3.one * Mathf.Max(0.001f, d));
        }

        static void SetGroup(Transform g, bool on, Vector3 scale)
        {
            if (g == null) return;
            if (g.gameObject.activeSelf != on) g.gameObject.SetActive(on);
            if (on) g.localScale = scale;
        }

        static float EaseOutBack(float t)
        {
            const float c1 = 1.4f, c3 = c1 + 1f;
            float x = t - 1f;
            return 1f + c3 * x * x * x + c1 * x * x;
        }

        public void SetGhost(Material ghostMaterial, bool on)
        {
            if (on == _ghost) return;
            var rs = Renderers;
            if (on)
            {
                _originalMats = new Material[rs.Length][];
                for (int i = 0; i < rs.Length; i++)
                {
                    _originalMats[i] = rs[i].sharedMaterials;
                    var arr = new Material[_originalMats[i].Length];
                    for (int k = 0; k < arr.Length; k++) arr[k] = ghostMaterial;
                    rs[i].sharedMaterials = arr;
                    rs[i].shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
                }
                if (_hitArea != null) _hitArea.enabled = false;
            }
            else if (_originalMats != null)
            {
                for (int i = 0; i < rs.Length && i < _originalMats.Length; i++)
                {
                    rs[i].sharedMaterials = _originalMats[i];
                    rs[i].SetPropertyBlock(null);
                    rs[i].shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.On;
                }
                if (_hitArea != null) _hitArea.enabled = true;
            }
            _ghost = on;
        }

        public void SetGhostTint(Color c)
        {
            if (!_ghost) return;
            if (_mpb == null) _mpb = new MaterialPropertyBlock();
            _mpb.SetColor(BaseColorId, c);
            foreach (var r in Renderers) r.SetPropertyBlock(_mpb);
        }

        public virtual void SetConnections(int neighbourMask) { }

        [Header("Level variants (index 0 = level 1; empty = one look for all levels)")]
        [SerializeField] private GameObject[] _levelRoots = new GameObject[0];

        public int Level { get; private set; } = 1;
        public int LevelVariantCount => _levelRoots != null ? _levelRoots.Length : 0;

        public void ConfigureLevels(GameObject[] roots) { _levelRoots = roots; }

        /// <summary>Shows the model of a level (highest configured variant ≤ level). Footprint and pivot never change.</summary>
        public void SetLevel(int level)
        {
            Level = Mathf.Max(1, level);
            if (_levelRoots == null || _levelRoots.Length == 0) return;
            int idx = Mathf.Clamp(Level - 1, 0, _levelRoots.Length - 1);
            for (int i = 0; i < _levelRoots.Length; i++)
                if (_levelRoots[i] != null && _levelRoots[i].activeSelf != (i == idx)) _levelRoots[i].SetActive(i == idx);
            _renderers = null; // ghost / highlight / bounds use the visible variant
        }

        public void Pop() => _pop = 0f;

        protected virtual void Update()
        {
            if (_moving)
            {
                transform.position = Vector3.SmoothDamp(transform.position, _targetPos, ref _vel, 0.06f, Mathf.Infinity, Time.unscaledDeltaTime);
                if ((transform.position - _targetPos).sqrMagnitude < 1e-6f) { transform.position = _targetPos; _moving = false; }
            }
            if (_pop >= 0f)
            {
                _pop += Time.unscaledDeltaTime / 0.42f;
                float a = Mathf.Clamp01(_pop);
                float s = Mathf.Sin(a * Mathf.PI) * (1f - a);
                ViewRoot.localScale = new Vector3(1f + s * 0.18f, 1f - s * 0.14f, 1f + s * 0.18f);
                if (a >= 1f) { _pop = -1f; ViewRoot.localScale = Vector3.one; }
            }
        }

        /// <summary>Renderers' world bounds (selection framing).</summary>
        public Bounds WorldBounds()
        {
            var b = new Bounds(transform.position, Vector3.one * 0.5f);
            bool first = true;
            foreach (var r in Renderers)
            {
                if (r == null || !r.gameObject.activeInHierarchy) continue;
                if (first) { b = r.bounds; first = false; } else b.Encapsulate(r.bounds);
            }
            return b;
        }
    }
}